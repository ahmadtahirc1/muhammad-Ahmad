export default function QRPlaceholder({ size = 152 }: { size?: number }) {
  const cells: { x: number; y: number }[] = [];
  for (let y = 0; y < GRID; y++) {
    for (let x = 0; x < GRID; x++) {
      if (ROWS[y][x] === "1") cells.push({ x, y });
    }
  }

  return (
    <div
      className="relative shrink-0 rounded-xl border border-border-strong bg-white p-2"
      style={{ width: size, height: size }}
    >
      <svg viewBox={`0 0 ${GRID} ${GRID}`} width="100%" height="100%" shapeRendering="crispEdges">
        {cells.map(({ x, y }) => (
          <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill="#0a0a0c" />
        ))}
      </svg>
    </div>
  );
}
